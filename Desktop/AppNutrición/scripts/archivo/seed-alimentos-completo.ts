async function main() {
  const totalAlimentos = ALL_DATA.reduce((sum, [, items]) => sum + items.length, 0);
  console.log(`\n=== Seed de ${totalAlimentos} alimentos básicos ===\n`);

  // 1. Limpiar BD
  console.log("Limpiando BD...");

  // Quitar referencias de alimentos en comidas
  await prisma.alimentoEnComida.updateMany({
    where: { alimentoId: { not: null } },
    data: { alimentoId: null },
  });
  console.log("  → Referencias en AlimentoEnComida limpiadas");

  // Quitar referencias en recetas (borrar ingredientes)
  await prisma.recetaIngrediente.deleteMany({});
  console.log("  → RecetaIngredientes eliminados");

  // Quitar referencias en diario
  await prisma.entradaDiario.updateMany({
    where: { alimentoId: { not: null } },
    data: { alimentoId: null },
  });
  console.log("  → Referencias en EntradaDiario limpiadas");

  // Borrar todos los alimentos
  await prisma.alimento.deleteMany({});
  console.log("  → Todos los alimentos eliminados\n");

  // 2. Insertar por categoría en lotes
  let total = 0;
  for (const [categoria, items] of ALL_DATA) {
    const data = items.map(([nombre, cal, prot, carb, gras, fibra, porcion]) => ({
      nombre: normalizarNombreAlimento(nombre),
      nombreNormalizado: normalizarParaBusqueda(nombre),
      categoria: categoria as Cat,
      calorias: redondearMacros(cal),
      proteinas: redondearMacros(prot),
      carbohidratos: redondearMacros(carb),
      grasas: redondearMacros(gras),
      fibra: redondearMacros(fibra),
      porcion,
      unidad: "GRAMOS" as const,
      origen: "PERSONALIZADO" as const,
      dietistaId: null,
    }));

    await prisma.alimento.createMany({ data });
    total += items.length;
    console.log(`  ${categoria}: ${items.length} alimentos`);
  }

  console.log(`\n✓ ${total} alimentos insertados correctamente`);
  console.log("=== Seed completado ===\n");
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
